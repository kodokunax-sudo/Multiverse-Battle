-- Realtime notifications allow the recipient's online game to receive gifts immediately.
do $$
begin
    if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
       and not exists (
           select 1 from pg_publication_tables
           where pubname = 'supabase_realtime'
             and schemaname = 'public'
             and tablename = 'clan_card_gifts'
       ) then
        execute 'alter publication supabase_realtime add table public.clan_card_gifts';
    end if;
end;
$$;
